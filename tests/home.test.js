import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {renderHome} from '../home.js';
const root=path.resolve(import.meta.dirname,'..');
test('home comercial: seções, navegação real, imagens locais e copy sem métricas fictícias',()=>{
 const html=renderHome();
 for(const id of ['solucoes','modelos','funcionalidades','como-funciona','perguntas'])assert.match(html,new RegExp(`id="${id}"`));
 assert.match(html,/<html lang="pt-BR">/);
 assert.match(html,/href="\/montar"/);
 assert.match(html,/href="\/igreja\/entrar"/);
 assert.match(html,/href="\/acompanhar"/);
 assert.match(html,/Monte seu plano/);
 assert.match(html,/Contratação por módulos/);
 for(const category of ["Site e presença digital","Membros e visitantes","Ministérios e cultos","Mídia e comunicação visual"])assert.ok(html.includes(category));
 assert.match(html,/href="\/montar\?modelo=moderno"/);
 assert.match(html,/ainda não/i);
 assert.doesNotMatch(html,/clientes satisfeitos|igrejas atendidas|100% de satisfação/i);
 for(const match of html.matchAll(/(?:src|href)="(\/assets\/[a-z0-9-]+\.webp)"/g))assert.ok(fs.existsSync(path.join(root,'public',match[1])),`Asset ausente: ${match[1]}`);
 assert.ok(fs.existsSync(path.join(root,'public','home.css')));
 assert.ok(fs.existsSync(path.join(root,'public','home.js')));
});
